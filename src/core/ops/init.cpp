// Create .gitignore file from templates
auto create_gitignore(const std::filesystem::path& repo_path, const std::vector<ProjectType>& types)
    -> Result<void> {
    if (types.empty()) {
        return {}; // No templates selected, success
    }

    auto gitignore_path = repo_path / ".gitignore";

    // Check if .gitignore already exists
    if (std::filesystem::exists(gitignore_path)) {
        // Don't modify existing file as per user requirement
        return {};
    }

    // Merge all templates
    std::ostringstream content;
    content << "# Generated by repo init\n";
    content << "# Created: " << std::chrono::system_clock::now() << "\n\n";

    for (const auto& type : types) {
        auto template_content = get_template(type);
        if (!template_content.empty()) {
            content << template_content << "\n";
        }
    }

    // Write to file
    std::ofstream file(gitignore_path);
    if (!file) {
        return std::unexpected(make_error(Error::Code::Unknown, "Failed to create .gitignore file",
                                          gitignore_path.string()));
    }

    file << content.str();

    if (!file) {
        return std::unexpected(make_error(Error::Code::Unknown, "Failed to write .gitignore file",
                                          gitignore_path.string()));
    }

    return {};
}

