// Initialize a new Git repository
auto init(const InitParams& params) -> Result<InitResult> {
    // Initialize the repository using Repository::init()
    repo::InitOptions opts{.bare = params.bare};

    // Note: initial_branch_name is ignored for now as Repository::InitOptions doesn't support it
    // yet
    // TODO: Add initial_branch_name support to Repository::InitOptions in the future

    auto repo_result = Repository::init(params.path, opts);
    if (!repo_result.has_value()) {
        return std::unexpected(repo_result.error());
    }

    auto& repo = *repo_result;

    InitResult result{
        .git_dir = repo.git_dir(), .created_gitignore = false, .applied_templates = {}};

    // Create .gitignore if project types specified
    if (!params.project_types.empty()) {
        auto gitignore_result = create_gitignore(params.path, params.project_types);
        if (!gitignore_result.has_value()) {
            // .gitignore creation failed, but repo was created - continue
            // (We could optionally return the error here if strict behavior is desired)
        } else {
            result.created_gitignore = true;
            result.applied_templates = params.project_types;
        }
    }

    return result;
}

