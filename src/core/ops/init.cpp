// Helper: Check if build system is relevant for given languages
auto is_build_system_relevant(ProjectType build_system, const std::vector<ProjectType>& languages)
    -> bool {
    // If no languages selected, show all build systems
    if (languages.empty()) {
        return true;
    }

    // Define which build systems are relevant for which languages
    static const std::unordered_map<ProjectType, std::unordered_set<ProjectType>> relevance_map = {
        // C++ build systems
        {ProjectType::CMake, {ProjectType::Cpp}},
        {ProjectType::Make, {ProjectType::Cpp}},
        {ProjectType::Vcpkg, {ProjectType::Cpp}},
        {ProjectType::Conan, {ProjectType::Cpp}},

        // Java/Kotlin build systems
        {ProjectType::Gradle, {ProjectType::Java, ProjectType::Kotlin}},
        {ProjectType::Maven, {ProjectType::Java, ProjectType::Kotlin}},
    };

    auto it = relevance_map.find(build_system);
    if (it == relevance_map.end()) {
        // Not a build system, always show
        return true;
    }

    const auto& relevant_languages = it->second;

    // Check if any selected language is in the relevant set
    for (const auto& lang : languages) {
        if (relevant_languages.count(lang) > 0) {
            return true;
        }
    }

    return false;
}

